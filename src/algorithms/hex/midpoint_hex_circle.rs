// ── Exact incremental recurrence ──────────────────────────────────────────────

/// The initial decision parameter mandated by the supplied definition.
pub const INITIAL_P: i32 = 3;

/// Result of one midpoint step, in axial hex coordinates.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Step {
    pub x: i32,
    pub y: i32,
    pub p: i32,
}

/// Apply exactly one midpoint step.
///
/// The decision uses the incoming `p`; both updated values are computed from
/// the incoming `x` and `y` before any assignment, so no coordinate can leak
/// into its own decision formula.
#[inline]
pub fn step(p: i32, x: i32, y: i32) -> Step {
    if p < 0 {
        let next_p = p + 8 * x + 4 * y + 10;
        let next_x = x + 1;
        Step {
            x: next_x,
            y,
            p: next_p,
        }
    } else {
        let next_p = p + 4 * x - 4 * y + 10;
        let next_x = x + 1;
        let next_y = y - 1;
        Step {
            x: next_x,
            y: next_y,
            p: next_p,
        }
    }
}

/// Exact decision function implied by the recurrences and `p₀ = 3` at `(0, r)`.
///
/// Purely integer. Exposed so tests can check that [`step`] preserves the
/// invariant rather than merely reproducing its own arithmetic.
#[inline]
pub fn decision_value(x: i32, y: i32, radius: i32) -> i64 {
    let x = x as i64;
    let y = y as i64;
    let r = radius as i64;
    4 * (x * x + x * y + y * y) + 6 * x + 3 - 4 * r * r
}

/// Axial coordinates of the first cell of the sector for `radius`.
#[inline]
pub fn sector_start(radius: i32) -> (i32, i32) {
    (0, radius.max(0))
}

/// 60° rotation about the origin, integer-only (paper §3).
///
/// `R(x, y) = (-y, x + y)`. Under mapping A this is a genuine +60° rotation,
/// and it preserves `F`: `F(-y, x+y) = x² + xy + y² = F(x, y)`.
#[inline]
pub fn rotate60(x: i32, y: i32) -> (i32, i32) {
    (-y, x + y)
}

/// Reflection in the `x == y` diagonal, integer-only (paper §3).
///
/// `S(x, y) = (y, x)`. It preserves `F` because the quadratic form is symmetric.
#[inline]
pub fn reflect(x: i32, y: i32) -> (i32, i32) {
    (y, x)
}

/// The 12 images of one cell under the hexagonal symmetry group.
///
/// Six rotations of the cell, followed by six rotations of its reflection:
/// `{Rⁱ(x,y)} ∪ {RⁱS(x,y)}` for `i = 0..6`. This is the 12-point symmetry
/// described in §3 / Figure 4 of the paper.
pub fn symmetry_images(x: i32, y: i32) -> [(i32, i32); 12] {
    let mut out = [(0, 0); 12];
    let mut cur = (x, y);
    for image in out.iter_mut().take(6) {
        *image = cur;
        cur = rotate60(cur.0, cur.1);
    }
    let mut cur = reflect(x, y);
    for image in out.iter_mut().skip(6) {
        *image = cur;
        cur = rotate60(cur.0, cur.1);
    }
    out
}

/// Walk the single 30° sector from `(0, r)` to the `x == y` diagonal.
///
/// The loop condition is `x <= y` (see the module docs for why the paper's
/// double-step `x < y` must be adjusted for this single-step walk).
pub fn sector_points(radius: i32) -> Vec<Point> {
    let mut out = Vec::new();
    let (mut x, mut y) = sector_start(radius);
    let mut p = INITIAL_P;

    while x <= y {
        out.push(Point { x, y });
        let next = step(p, x, y);
        x = next.x;
        y = next.y;
        p = next.p;
    }
    out
}

/// The complete circle: all 12 symmetry images of the 30° sector.
///
/// The only duplicates arise on the two reflection axes bounding the sector —
/// `x == 0` (the start cell, whose reflected orbit equals its rotated orbit)
/// and `x == y` (fixed by `S`). Those cells are shared by adjacent sectors, so
/// a single deduplication is required; it is not used to hide off-sector cells.
pub fn circle_points(radius: i32) -> Vec<Point> {
    let mut seen = HashSet::new();
    let mut out = Vec::new();
    for cell in sector_points(radius) {
        for (x, y) in symmetry_images(cell.x, cell.y) {
            if seen.insert((x, y)) {
                out.push(Point { x, y });
            }
        }
    }
    out
}

// ── The algorithm ─────────────────────────────────────────────────────────────

/// Selectable hexagonal midpoint-circle algorithm.
#[derive(Clone)]
pub struct MidpointHexCircle {
    pub radius: i32,
    pub world_half: i32,
    pub show_ideal_circle: bool,
    points: Vec<Point>,
}

impl Default for MidpointHexCircle {
    fn default() -> Self {
        let mut s = Self {
            radius: 5,
            world_half: 12,
            show_ideal_circle: true,
            points: Vec::new(),
        };
        s.compute();
        s
    }
}

impl MidpointHexCircle {
    /// Build the full hex-grid geometry: background tiling, rasterised cells,
    /// optional ideal circle, and hover/selection highlights.
    pub fn build_geometry(
        &self,
        mouse_cell: Option<(i32, i32)>,
        selected_cell: Option<(i32, i32)>,
    ) -> crate::algorithms::hex::ExperimentGeometry {
        let mut lines = Vec::<Vertex>::new();
        let mut quads = Vec::<Vertex>::new();

        // Reuse the existing experiment's region generator unchanged.
        let grid = HexGridExperiment {
            world_half: self.world_half,
            ..HexGridExperiment::default()
        };
        let cells = grid.region_cells();

        // Background tiling. All cell centres use the same render-space
        // transform as the polygons, so overlays stay aligned with the grid.
        for &(x, y) in &cells {
            let (cx, cy) = hex_to_world(x, y);
            push_hex_fill(&mut quads, cx, cy, [0.30, 0.30, 0.34, 0.30]);
        }
        for &(x, y) in &cells {
            let (cx, cy) = hex_to_world(x, y);
            push_hex_outline(&mut lines, cx, cy, [0.22, 0.22, 0.26, 1.0]);
        }

        // The rasterised outline, as bright filled and outlined hex cells.
        for cell in &self.points {
            let (cx, cy) = hex_to_world(cell.x, cell.y);
            push_hex_fill(&mut quads, cx, cy, [0.0, 0.78, 1.0, 0.75]);
            push_hex_outline(&mut lines, cx, cy, [0.0, 0.90, 1.0, 1.0]);
        }

        // Ideal circle for comparison (same construction as the experiment).
        if self.show_ideal_circle && self.radius > 0 {
            let segments = 180usize;
            let rf = self.radius as f32;
            for i in 0..segments {
                let a0 = 2.0 * std::f32::consts::PI * i as f32 / segments as f32;
                let a1 = 2.0 * std::f32::consts::PI * (i + 1) as f32 / segments as f32;
                lines.push(Vertex::new(
                    rf * a0.cos(),
                    rf * a0.sin(),
                    1.0,
                    1.0,
                    1.0,
                    0.9,
                ));
                lines.push(Vertex::new(
                    rf * a1.cos(),
                    rf * a1.sin(),
                    1.0,
                    1.0,
                    1.0,
                    0.9,
                ));
            }
        }

        // Hover and selection, in the same axial coordinates as input.rs.
        if let Some((hx, hy)) = mouse_cell {
            let (cx, cy) = hex_to_world(hx, hy);
            push_hex_fill(&mut quads, cx, cy, [0.5, 0.7, 1.0, 0.15]);
            push_hex_outline(&mut lines, cx, cy, [0.5, 0.7, 1.0, 0.9]);
        }
        if let Some((sx, sy)) = selected_cell {
            let (cx, cy) = hex_to_world(sx, sy);
            push_hex_fill(&mut quads, cx, cy, [1.0, 1.0, 0.0, 0.45]);
            push_hex_outline(&mut lines, cx, cy, [1.0, 1.0, 0.0, 1.0]);
        }

        crate::algorithms::hex::ExperimentGeometry {
            line_verts: lines,
            quad_verts: quads,
        }
    }
}

impl Algorithm for MidpointHexCircle {
    fn name(&self) -> &str {
        "Midpoint Circle (hex)"
    }

    fn category(&self) -> &'static str {
        "hex"
    }

    fn compute(&mut self) {
        self.points = circle_points(self.radius);
    }

    fn points(&self) -> &[Point] {
        &self.points
    }

    fn color(&self) -> [f32; 3] {
        [0.0, 0.78, 1.0]
    }

    fn draw_ui(&mut self, ui: &mut egui::Ui) -> bool {
        let mut changed = false;
        ui.label("Hex midpoint circle — 30° sector, 12-way symmetry (paper §3–4)");
        ui.separator();
        changed |= ui
            .add(egui::Slider::new(&mut self.radius, 1..=20).text("Radius r"))
            .changed();
        changed |= ui
            .add(
                egui::Slider::new(&mut self.world_half, 4..=40)
                    .text("Region half-extent (world units)"),
            )
            .changed();
        changed |= ui
            .checkbox(&mut self.show_ideal_circle, "Ideal circle F = r²")
            .changed();
        ui.separator();
        ui.label("Cyan = rasterised hex cells. White = ideal circle.");
        ui.label("Single-step loop stops at x == y; boundary cell included.");
        changed
    }

    fn viewport(&self) -> Option<(f32, f32, f32)> {
        Some((0.0, 0.0, self.world_half as f32 + 1.0))
    }

    fn overlay_geometry(
        &self,
        mouse_cell: Option<(i32, i32)>,
        selected_cell: Option<(i32, i32)>,
    ) -> Option<crate::algorithms::hex::ExperimentGeometry> {
        Some(self.build_geometry(mouse_cell, selected_cell))
    }

    fn cell_info(&self, cx: i32, cy: i32) -> Option<String> {
        let r2 = self.radius as i64 * self.radius as i64;
        Some(format!(
            "axial ({cx}, {cy})  cube s={}\nF = {}\nr² = {r2}\np(F-based) = {}",
            -cx - cy,
            crate::algorithms::hex::f_quadratic(cx, cy),
            decision_value(cx, cy, self.radius),
        ))
    }
}

