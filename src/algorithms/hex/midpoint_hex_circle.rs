    #[test]
    fn duplicates_come_only_from_the_two_shared_sector_boundaries() {
        // The 12 images of a cell are distinct unless the cell lies on a
        // reflection axis. In the sector those axes are x == 0 (start) and
        // x == y (final diagonal cell). Only those may be deduplicated.
        for r in 1..=20 {
            for cell in sector_points(r) {
                let images = symmetry_images(cell.x, cell.y);
                let unique: HashSet<(i32, i32)> = images.iter().copied().collect();
                let on_axis = cell.x == 0 || cell.x == cell.y;
                if on_axis {
                    assert_eq!(unique.len(), 6, "r={r}, cell=({},{})", cell.x, cell.y);
                } else {
                    assert_eq!(unique.len(), 12, "r={r}, cell=({},{})", cell.x, cell.y);
                }
            }
        }
    }

    #[test]
    fn final_circle_is_centred_and_symmetry_closed_for_small_radii() {
        for r in 1..=12 {
            let pts = circle_points(r);
            let set: HashSet<(i32, i32)> = pts.iter().map(|p| (p.x, p.y)).collect();

            // Centred on the axial origin.
            let sx: i64 = pts.iter().map(|p| p.x as i64).sum();
            let sy: i64 = pts.iter().map(|p| p.y as i64).sum();
            assert_eq!(sx, 0, "x centroid r={r}");
            assert_eq!(sy, 0, "y centroid r={r}");

            // Closed under every symmetry operation.
            for p in &pts {
                for (x, y) in symmetry_images(p.x, p.y) {
                    assert!(set.contains(&(x, y)), "r={r}: missing image ({x},{y})");
                }
            }

            // All cells lie on lattice rings close to r² (a 30% band is enough
            // to catch a wrong sector without demanding exact F == r²).
            let r2 = (r as i64) * (r as i64);
            for p in &pts {
                let f = crate::algorithms::hex::f_quadratic(p.x, p.y);
                assert!((f - r2).abs() <= r2.max(1) / 3, "r={r}, cell F={f}");
            }
        }
    }

    #[test]
    fn generated_geometry_and_viewport_use_the_existing_hex_infrastructure() {
        let algo = MidpointHexCircle::default();
        assert_eq!(
            algo.viewport(),
            Some((0.0, 0.0, algo.world_half as f32 + 1.0))
        );
        assert_eq!(algo.category(), "hex");

        let geom = algo.overlay_geometry(Some((1, 2)), Some((3, 4))).unwrap();
        assert!(!geom.quad_verts.is_empty());
        assert!(!geom.line_verts.is_empty());
        // Each rasterised cell contributes a 6-triangle fill (18 vertices).
        let expected_cells = algo.points.len() + grid_cell_count(algo.world_half) + 2;
        assert_eq!(geom.quad_verts.len(), expected_cells * 18);
    }

    /// Number of background cells, from the same bounds as `region_cells`.
    fn grid_cell_count(world_half: i32) -> usize {
        HexGridExperiment {
            world_half,
            ..HexGridExperiment::default()
        }
        .region_cells()
        .len()
    }
