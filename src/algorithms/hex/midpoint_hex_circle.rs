//! Hexagonal-grid midpoint circle (Bresenham-family), isolated research algorithm.
//!
//! This module implements only the recurrence supplied for this experiment:
//!
//! ```text
//! p0 = 3
//! p <  0 : (x, y) -> (x + 1, y)     , p' = p + 8x + 4y + 10
//! p >= 0 : (x, y) -> (x + 1, y - 1) , p' = p + 4x - 4y + 10
//! ```
//!
//! The condition is evaluated on the **current** `p`, and every `p'` uses the
//! **old** `x` and `y`. See [`step`], which keeps the two updates separate so
//! this can be inspected directly.
//!
//! # Why the initial coordinate is `(0, r)`
//!
//! The recurrences are exact increments of
//!
//! ```text
//! p(x, y) = 4·F(x, y) + 6x + 3 - 4r² ,   F(x, y) = x² + xy + y²
//! ```
//!
//! (verified by [`decision_value`] and its tests). At `(0, r)` this gives
//! `p = 4r² + 0 + 3 - 4r² = 3`, so `p₀ = 3` fixes the start at `(0, r)` under
//! the existing mapping-A hex coordinates. This is also the same starting
//! cell used by `circle::midpoint_circle::MidpointCircle`. No centre offset is
//! introduced: the existing hex rendering/input infrastructure is centred on
//! the axial origin.
//!
//! # Sector definition and termination (paper §4 / Algorithm 1)
//!
//! Following Manoharan & Ray, *An Improved Circle Drawing Algorithm on a
//! Hexagonal Grid* (Journal of Graphics Tools, 2013, 17(1–2):5–15), the walk
//! starts at `(0, r)` with `p = 3` and generates **one 30° sector**, bounded by
//! the 90° axis (`x == 0`) and the 60° diagonal (`x == y` under mapping A).
//!
//! The paper's Algorithm 1 is **double-step** and writes `while x < y`. This
//! implementation is **single-step** (one cell per loop, exactly one call to
//! [`step`]), so copying that condition verbatim would omit the diagonal
//! boundary cell whenever the walk lands exactly on it (e.g. `r = 2` ends at
//! `(1, 1)`, `r = 5` at `(3, 3)`, `r = 7` at `(4, 4)`). The single-step
//! equivalent is therefore `while x <= y`: it includes that boundary cell and
//! emits no cell with `x > y`, i.e. nothing outside the 30° sector.
//!
//! # 12-way symmetry (paper §3 / Figure 4)
//!
//! The full circle is generated by the dihedral group of the hexagon: six
//! rotations `Rⁱ` and six reflected rotations `Rⁱ ∘ S`, with the **integer-only**
//! generators
//!
//! ```text
//! R(x, y) = (-y, x + y)    (60° rotation)
//! S(x, y) = (y, x)         (reflection)
//! ```
//!
//! Both preserve `F(x, y) = x² + xy + y²`, and both are integer maps, so the
//! symmetry stage introduces no floating point. See [`rotate60`], [`reflect`],
//! and [`symmetry_images`].
//!
//! Duplicate cells are expected only on the two reflection axes that bound
//! adjacent sectors: the start cell `x == 0` (where `S(0,r) = R⁵(0,r)`) and the
//! diagonal `x == y` (fixed by `S`). They are removed once with a `HashSet` for
//! exactly that reason, never to mask off-sector generation. See
//! [`circle_points`] and its tests.

use std::collections::HashSet;

